#!/usr/bin/env python3
"""Generate 256-entry 8-bit sine LUT hex (offset-binary, mid=128).

Math: val[i] = round(128 + 127*sin(2*pi*i/256)) clipped to [0,255].
Writes design/digital/sine_lut.hex (one 2-digit hex per line).
"""
import math
from pathlib import Path

N = 256
out = Path(__file__).resolve().parents[1] / "design" / "digital" / "sine_lut.hex"
vals = []
for i in range(N):
    v = int(round(128 + 127 * math.sin(2 * math.pi * i / N)))
    v = max(0, min(255, v))
    vals.append(v)
out.write_text("\n".join(f"{v:02x}" for v in vals) + "\n")
# Synth-safe ROM: pure-Verilog case table, no $readmemh file dependency,
# so sim and LibreLane synthesis elaborate IDENTICAL logic from one source.
rom = ["// sine_rom.v — generated by scripts/gen_lut.py. Do not hand-edit.",
       "`default_nettype none",
       "module sine_rom (",
       "    input  wire [7:0] addr,",
       "    output reg  [7:0] dout",
       ");",
       "    always @* begin",
       "        case (addr)"]
rom += [f"            8'd{i}: dout = 8'h{v:02x};" for i, v in enumerate(vals)]
rom += ["            default: dout = 8'h80;",
        "        endcase",
        "    end",
        "endmodule",
        "`default_nettype wire",
        ""]
rom_path = out.parent / "sine_rom.v"
rom_path.write_text("\n".join(rom))
print(f"wrote {rom_path} (case ROM)")
print("first 8:", [f"{v:02x}" for v in vals[:8]])
print("idx64 (peak):", f"{vals[64]:02x}={vals[64]}", "idx192 (trough):", f"{vals[192]:02x}={vals[192]}")
